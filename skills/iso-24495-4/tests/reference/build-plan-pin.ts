// The command that regenerates `../fixtures/plan-pin.ts`:
//
//   bun skills/iso-24495-4/tests/reference/build-plan-pin.ts
//
// The fixture records what `planDocument` makes of each document in
// `plan-pin-entries.ts`: every request a Jev audit would send, and every
// finding it makes without sending. A test fails when the record and the code
// disagree. The calibration files that pin the same thing are not shipped, so
// the test that reads them is skipped in the gate; this one always runs.
//
// Run the command only for a change meant to alter a Jev request, and read
// the fixture's diff as the record of what changed. A parser edit for an
// offline rule should leave the fixture as it is.
//
// It writes where told, so a test can rebuild the fixture without touching it.

import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { planPinEntries } from "./plan-pin-entries.ts";

const FIXTURE = process.argv[2] ?? join(import.meta.dir, "..", "fixtures", "plan-pin.ts");

const entries = planPinEntries();
const body = Object.entries(entries).map(([name, record]) => `  ${JSON.stringify(name)}: ${JSON.stringify(record)},`).join("\n");

const contents = `// Generated by ../reference/build-plan-pin.ts. Do not edit by hand.
//
// What planDocument makes of each document the plan pin covers. Read a diff
// here as a change to what a Jev audit sends.

import type { PlanRecord } from "../reference/plan-pin-entries.ts";

/** What planDocument made of each covered document, by name. */
export const PLAN_PIN: Record<string, PlanRecord> = {
${body}
};
`;

writeFileSync(FIXTURE, contents, "utf8");
console.log(`wrote ${Object.keys(entries).length} plans to ${FIXTURE}`);
